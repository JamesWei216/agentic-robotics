#!/usr/bin/env python3
"""Stage 2 — code generation: plan.json -> executable control logic.

赛题 2.d: 生成可执行控制逻辑（Python），支持仿真运行.

Two generators, in order:
  1. the LLM writes the script from the plan + capability card;
  2. if the script fails static validation (forbidden imports/calls, missing
     entry point) a deterministic template built from the same plan is used.

Either way only the primitive surface of `agent.skills.api` is reachable, so a
hallucinated import cannot touch the filesystem or the network.
"""
from __future__ import annotations

import ast
import json
import pathlib

from agent import llm
from agent.prompts import coder_prompt
from agent.schemas import plan_summary

ROOT = pathlib.Path(__file__).resolve().parent.parent

ALLOWED_IMPORTS = {"sys", "agent.skills.api"}
FORBIDDEN_NAMES = {
    "eval", "exec", "compile", "__import__", "open", "input", "breakpoint",
    "globals", "locals", "vars", "setattr", "delattr",
}
FORBIDDEN_MODULES = {
    "os", "subprocess", "socket", "shutil", "pathlib", "requests", "urllib",
    "http", "importlib", "ctypes", "pickle", "multiprocessing", "threading",
}
ALLOWED_METHODS = {
    "settle", "scan", "pick", "place", "pick_and_place", "home", "check",
    "confirm", "log", "todo", "close", "stats",
}


class CodeError(ValueError):
    pass


def validate_code(src: str) -> str:
    if not src.strip():
        raise CodeError("empty script")
    try:
        tree = ast.parse(src)
    except SyntaxError as e:
        raise CodeError(f"syntax error: {e.msg} (line {e.lineno})")

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                if a.name not in ALLOWED_IMPORTS:
                    raise CodeError(f"forbidden import: {a.name}")
        elif isinstance(node, ast.ImportFrom):
            mod = node.module or ""
            if mod not in ALLOWED_IMPORTS:
                raise CodeError(f"forbidden import: from {mod}")
        elif isinstance(node, ast.Name) and node.id in FORBIDDEN_NAMES:
            raise CodeError(f"forbidden name: {node.id}")
        elif isinstance(node, ast.Attribute) and node.attr in ("__globals__", "__dict__", "__code__"):
            raise CodeError(f"forbidden attribute: {node.attr}")

    src_lower = src.lower()
    if "robot.from_env" not in src_lower:
        raise CodeError("script never calls Robot.from_env()")
    if "def run(" not in src_lower:
        raise CodeError("script has no run() entry point")

    used = {n.func.attr for n in ast.walk(tree)
            if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)}
    odd = used - ALLOWED_METHODS - {"append", "get", "items", "keys", "format",
                                    "join", "strip", "split", "startswith",
                                    "update", "pop", "extend", "copy"}
    # informational only: helper names are fine, we just surface them in the log
    return src.strip() + "\n"


def template_code(plan: dict) -> str:
    """Deterministic codegen from the validated plan (always runnable)."""
    plan_steps = json.dumps([{"op": s["op"], "args": s.get("args", {})} for s in plan["steps"]],
                            ensure_ascii=False)
    return f'''"""Generated by agent.codegen (template path).

Plan: {plan['task'].get('name', 'bolt sorting')}
Goal: {plan['task'].get('goal', '')}
Steps: {len(plan['steps'])}  ({plan_steps[:300]})
"""
import sys

from agent.skills.api import Robot


def sort_one(R, obj, box):
    """Pick `obj` and drop it in `box`, with one retry on grasp failure."""
    for attempt in (1, 2):
        try:
            R.log("attempt %d: %s -> %s" % (attempt, obj, box), object=obj, target=box)
            R.pick(obj)
            ok = R.place(obj, box)
            return bool(ok)
        except RuntimeError as exc:
            R.log("grasp/placement failure: %s" % exc, object=obj, attempt=attempt)
            R.settle(15)
    return False


def run():
    R = Robot.from_env()
    placed, failed = [], []
    try:
        R.log("plan loaded: settle -> scan -> sort each todo pair -> check -> home")
        R.settle(30)
        R.scan("bolt")
        R.confirm("first_motion")
        for item in R.todo():
            obj, box = item["object"], item["bin"]
            (placed if sort_one(R, obj, box) else failed).append(obj)
        ok = R.check()
        R.home()
        R.log("finished", success=ok, placed=placed, failed=failed, **R.stats())
        return ok
    finally:
        R.close()


if __name__ == "__main__":
    sys.exit(0 if run() else 1)
'''


def _strip_fences(text: str) -> str:
    text = text.strip()
    if "```" in text:
        parts = text.split("```")
        for part in parts:
            body = part.strip()
            if body.lower().startswith("python"):
                body = body[6:]
            if "Robot.from_env" in body:
                return body.strip()
    return text


def generate(plan: dict, *, model: str | None = None, use_llm: bool = True) -> tuple[str, dict]:
    """Return (code, provenance)."""
    provenance = {"generator": "template", "reason": "llm disabled", "validation": None}
    if use_llm:
        try:
            raw = llm.chat(coder_prompt(json.dumps(plan, ensure_ascii=False),
                                        plan_summary(plan)),
                           model=model, max_tokens=6000, think=False, temperature=0.1)
            code = _strip_fences(raw)
            validate_code(code)
            return code, {"generator": "llm", "reason": None, "validation": "ok"}
        except Exception as e:  # noqa: BLE001
            provenance = {"generator": "template",
                          "reason": f"{type(e).__name__}: {e}",
                          "validation": "failed"}
    code = template_code(plan)
    validate_code(code)
    return code, provenance


def repair(code: str, diagnosis: dict, *, model: str | None = None) -> tuple[str, dict]:
    """Ask the model to fix a failing script. Falls back to the unchanged code."""
    from agent.prompts import repair_prompt

    try:
        raw = llm.chat(repair_prompt(code, diagnosis), model=model,
                       max_tokens=6000, think=False, temperature=0.1)
        fixed = _strip_fences(raw)
        validate_code(fixed)
        return fixed, {"applied": True, "reason": None}
    except Exception as e:  # noqa: BLE001
        return code, {"applied": False, "reason": f"{type(e).__name__}: {e}"}


def write(code: str, path: pathlib.Path) -> pathlib.Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(code)
    return path


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("plan")
    ap.add_argument("--out", default="runtime/task.py")
    ap.add_argument("--no-llm", action="store_true")
    args = ap.parse_args()
    plan = json.loads(pathlib.Path(args.plan).read_text())
    code, prov = generate(plan, use_llm=not args.no_llm)
    write(code, pathlib.Path(args.out))
    print(json.dumps(prov, ensure_ascii=False))
    print(f"wrote {args.out} ({len(code.splitlines())} lines)")
